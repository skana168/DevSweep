#[derive(Clone)]
pub struct Rule {
    pub id: String,
    /// `None` applies to every stack.
    pub stack: Option<Stack>,
    /// Literal relative path, with one `*` allowed inside a segment.
    pub rel: String,
    /// Display name for user-added rules; built-ins show their path instead.
    pub label: Option<String>,
    pub default_checked: bool,
    pub dangerous: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Target {
    pub rule_id: String,
    pub path: PathBuf,
    pub size: Option<u64>,
    /// The clean panel's draft choice; reset to `default_checked` each time it opens.
    pub checked: bool,
    pub default_checked: bool,
    pub dangerous: bool,
    pub label: Option<String>,
}

fn rule(id: &str, stack: Option<Stack>, rel: &str, default_checked: bool, dangerous: bool) -> Rule {
    Rule {
        id: id.to_string(),
        stack,
        rel: rel.to_string(),
        label: None,
        default_checked,
        dangerous,
    }
}

